let current: Lang = "zh-CN";

export function setLang(lang: string) {
  if (lang in dicts) current = lang as Lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: string, vars?: Record<string, string>): string {
  let s = dicts[current][key] ?? zhCN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}

/** 把 [data-i18n] / [data-i18n-title] / [data-i18n-placeholder] 属性标记的元素本地化 */
export function applyI18n(root: ParentNode = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n")!);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    (el as HTMLElement).title = t(el.getAttribute("data-i18n-title")!);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    (el as HTMLInputElement).placeholder = t(el.getAttribute("data-i18n-placeholder")!);
  });
  document.documentElement.lang = current;
}

/** 各窗口启动时调用：从后端读语言设置并应用 */
export async function initI18n() {
  try {
    const s = await invoke<{ language: string }>("get_settings");
    setLang(s.language);
  } catch {
    /* 用默认语言 */
  }
  applyI18n();
}
